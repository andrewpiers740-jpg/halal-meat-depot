// Wholesale packs: anything sold in a pack under MIN_PACK_KG is sold as a case
// of enough packs to reach it (e.g. 2 x 300g steaks → case of 4).
export const MIN_PACK_KG = 2

// p(category, subcategory, name, packLabel, packKg, perKg, short, desc, extra)
function p(cat, sub, name, packUnit, packKg, perKg, short, desc, extra = {}) {
  const slug = extra.slug || name.toLowerCase().replace(/&/g, 'and').replace(/[^a-z0-9]+/g, '-').replace(/(^-|-$)/g, '')
  const n = packKg < MIN_PACK_KG ? Math.ceil(MIN_PACK_KG / packKg) : 1
  const unit = n > 1 ? `case of ${n} (${packUnit})` : packUnit
  const kg = Math.round(packKg * n * 1000) / 1000
  return {
    slug,
    name,
    cat,
    sub,
    unit,
    kg,
    packUnit,
    packKg,
    perKg,
    price: Math.round(kg * perKg * 100) / 100,
    short,
    desc,
    badge: extra.badge || null,
    featured: Boolean(extra.featured),
    images: [`${slug}-${IMAGE_VERSION}.webp`],
  }
}

