// Writes src/config/post-v4-index.js: the slim part of the v4 blog data (old slug -> new slug + focus keyword).
// site.js -> seo.js reach client bundles, so they must not import post-v4.js (it pulls in ~1.2 MB of post copy).
import fs from 'node:fs'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { resolve, dirname } from 'node:path'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const { POST_V4, POST_MOVES_V4 } = await import(pathToFileURL(resolve(root, 'src/config/post-v4.js')).href)
const index = Object.fromEntries(Object.entries(POST_V4).map(([old, v]) => [old, { slug: v.slug, kw: v.kw }]))
fs.writeFileSync(
  resolve(root, 'src/config/post-v4-index.js'),
  `// Generated by scripts/gen-post-v4-index.mjs (runs in prebuild); do not hand-edit.\n// Slim copy of post-v4.js for seo.js and client-reachable code: no post copy.\nexport const POST_V4_INDEX = ${JSON.stringify(index)}\nexport const POST_MOVES_V4 = ${JSON.stringify(POST_MOVES_V4)}\n`,
)
console.log('post-v4-index:', Object.keys(index).length, 'posts')
