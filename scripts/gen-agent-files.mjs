  `// Generated by scripts/gen-agent-files.mjs from POSTS — do not hand-edit.\nexport const POST_INDEX = ${JSON.stringify(POSTS.map((p) => ({ slug: p.slug, title: p.title, excerpt: p.excerpt, kw: p.kw })), null, 1)}\n`
