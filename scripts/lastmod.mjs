// Real <lastmod> dates for the sitemap (SEO audit H5). Each URL gets a fingerprint of the
// content that drives it; the stored date only moves when that fingerprint changes.
// Writes src/config/lastmod.js — commit it, so deploys keep the dates. Runs before dev/build.
import { readFileSync, writeFileSync, existsSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { createHash } from 'node:crypto'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const { PRODUCTS, CATEGORIES } = await import(pathToFileURL(resolve(root, 'src/config/site.js')))
const { PRODUCT_ABOUT } = await import(pathToFileURL(resolve(root, 'src/config/product-about.js')))
const { PRODUCT_KEYWORDS } = await import(pathToFileURL(resolve(root, 'src/config/product-keywords.js')))
const { STATIC_PAGES } = await import(pathToFileURL(resolve(root, 'src/lib/sitemaps.js')))
const file = resolve(root, 'src/config/lastmod.js')
const sha = (s) => createHash('sha256').update(s).digest('hex').slice(0, 16)
const read = (p) => (existsSync(p) ? readFileSync(p, 'utf8') : '')

// Shared templates change every page of a type, so they are part of each fingerprint.
const productTpl = read(resolve(root, 'src/app/(site)/product/[slug]/page.jsx')) + read(resolve(root, 'src/lib/productContent.js'))
const categoryTpl = read(resolve(root, 'src/app/(site)/shop/[cat]/page.jsx'))
const inputs = {}
for (const p of PRODUCTS) {
  const { name, unit, price, perKg, short, desc, focus, slug, badge } = p
  inputs[`/product/${p.slug}/`] = sha(JSON.stringify({ name, unit, price, perKg, short, desc, focus, slug, badge, about: PRODUCT_ABOUT[p.imageSlug], kw: PRODUCT_KEYWORDS[p.imageSlug] }) + productTpl)
}
for (const c of CATEGORIES) {
  const items = PRODUCTS.filter((p) => p.cat === c.slug).map((p) => [p.slug, p.price])
  inputs[c.path] = sha(JSON.stringify({ c, items }) + categoryTpl)
}
for (const path of STATIC_PAGES) {
  const page = path === '/' ? 'src/app/(site)/page.jsx' : `src/app/(site)${path}page.jsx`
  inputs[path] = sha(read(resolve(root, page)))
}

const prev = existsSync(file) ? (await import(pathToFileURL(file) + `?t=${Date.now()}`)).LASTMOD : {}
const now = new Date().toISOString()
const next = {}
let changed = 0
for (const [path, hash] of Object.entries(inputs)) {
  if (prev[path]?.hash === hash) next[path] = prev[path]
  else (next[path] = { hash, date: now }), changed++
}
writeFileSync(file, `// Generated by scripts/lastmod.mjs — real last-modified dates for the sitemap. Commit this file.\nexport const LASTMOD = ${JSON.stringify(next, null, 1)}\n`)
console.log(`lastmod: ${Object.keys(next).length} URLs, ${changed} changed`)
