// Owner (2026-11-02): new posts use the site's own product images, not licensed photos.
// For each new post: take the photos of its product-primary links, make 640/768/1024 WebP copies in
// public/images/blog/<slug>-<n>-<w>.webp and write src/config/new-post-images-v4.js.
// Usage: node scripts/gen-new-post-images.mjs [new-slug ...]   (no args = all new posts)
import fs from 'node:fs'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { resolve, dirname } from 'node:path'
import sharp from 'sharp'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const only = process.argv.length > 2 ? new Set(process.argv.slice(2)) : null
const { PRODUCTS } = await import(pathToFileURL(resolve(root, 'src/config/products.js')).href)
const { POST_KEYWORDS_V4 } = await import(pathToFileURL(resolve(root, 'src/config/post-keywords-v4.js')).href)
const outFile = resolve(root, 'src/config/new-post-images-v4.js')
let existing = {}
if (fs.existsSync(outFile)) existing = (await import(pathToFileURL(outFile).href + '?t=' + Date.now())).NEW_POST_IMAGES
const byLink = (l) => PRODUCTS.find((p) => `/product/${p.slug}/` === l)

for (const v of Object.values(POST_KEYWORDS_V4)) {
  if (!v.isNew || (only && !only.has(v.slug))) continue
  // product-primary links first, then any other product links; up to 4 distinct products
  const primary = v.keywords.filter((k) => k.product).map((k) => byLink(k.link))
  const others = v.keywords.filter((k) => !k.product && k.link).map((k) => byLink(k.link))
  const pick = [...new Set([...primary, ...others].filter(Boolean))].slice(0, 4)
  if (pick.length < 4) console.log('WARN fewer than 4 images for', v.slug, pick.length)
  const imgs = []
  for (let i = 0; i < pick.length; i++) {
    const p = pick[i]
    const src = resolve(root, 'public/images/products', p.images[0])
    for (const w of [640, 768, 1024]) {
      await sharp(src).resize(w, Math.round((w * 3) / 4)).webp({ quality: 72 }).toFile(resolve(root, `public/images/blog/${v.slug}-${i + 1}-${w}.webp`))
    }
    imgs.push({ n: i + 1, w: 1024, h: 768, alt: `${p.name}, certified halal and delivered by Halal Meat Depot`, own: true })
  }
  existing[v.slug] = imgs
}
fs.writeFileSync(
  outFile,
  `// Own images for the new v4 posts: the linked products' photos, resized to /images/blog/<slug>-<n>-<w>.webp.\n// Owner, 2026-11-02: normal site images, not licensed photos. Generated by scripts/gen-new-post-images.mjs; do not hand-edit.\nexport const NEW_POST_IMAGES = ${JSON.stringify(existing, null, 1)}\n`,
)
console.log('posts with images:', Object.keys(existing).length)
